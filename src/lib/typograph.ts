/* v64: типограф показа. Данные кейсов не трогаем (их сверяет tools/text-guard.mjs) — правим только то, что
   уходит в разметку: расставляем неразрывные пробелы, чтобы строка не кончалась предлогом, а число не отрывалось
   от своего слова. В русском наборе это базовая гигиена: «в», «и», «на» в конце строки — висячие предлоги.
   Правила:
   1) после слова в одну-две буквы (в, и, на, не, по, a, I, of, to…) пробел неразрывный;
   2) перед частицами «же», «бы», «ли», «б», «ж» пробел неразрывный;
   3) перед тире пробел неразрывный — тире не уезжает в начало строки;
   4) между числом и следующим словом (9 месяцев, 6 передач, 38 %) и вокруг стрелки «6 → 0»;
   5) последние два слова абзаца держатся вместе, если последнее короче шести букв — без «сироты» в конце.
   Регулярные выражения без lookbehind: старый Safari падает на них при разборе всего файла. */
const NB = " ";

const SHORT = /(^|[\s («„“"'])([A-Za-zА-Яа-яЁё]{1,2}) (?=\S)/g;
const PARTICLE = / (же|бы|ли|б|ж)(?=[\s.,;:!?»)]|$)/g;
const DASH = / ([—–])/g;
const NUMBER = /(\d[\d.,]*%?) (?=[A-Za-zА-Яа-яЁё%→₽$€])/g;
const ARROW = / ?→ ?/g;
const TAIL = / (\S{1,5})$/;

export function tidy(text: string): string {
  if (!text || text.indexOf(" ") < 0) return text;
  let s = text;
  /* дважды: в «и в доме» второй предлог начинается с пробела, который съело первое совпадение */
  s = s.replace(SHORT, `$1$2${NB}`).replace(SHORT, `$1$2${NB}`);
  s = s.replace(PARTICLE, `${NB}$1`);
  s = s.replace(DASH, `${NB}$1`);
  s = s.replace(NUMBER, `$1${NB}`);
  s = s.replace(ARROW, `${NB}→${NB}`);
  if (s.length > 40) s = s.replace(TAIL, `${NB}$1`);
  return s;
}
