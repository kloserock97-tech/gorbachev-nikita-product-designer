/* v115: контракт живого прототипа на странице кейса (caseProto.ts). Модуль — настоящий интерфейс в HTML/CSS/JS,
   собранный по макетам кейса; панель шагов слева и «почему так» рисует движок, модуль отвечает только за экран.

   Модуль верстает в своей «дизайн-ширине» (design.w: 393 для телефона, ~1100 для окна браузера), движок ужимает
   экран через CSS zoom под размер рамки; высота корня — сколько влезает в рамку при этой ширине. Внутри корня модуль
   сам решает, что прокручивается.

   Шаги — те же, что в данных кейса (prototype.steps): когда человек сделал нужное действие, модуль зовёт go(k),
   и движок переключает панель на шаг k. Обратно: человек нажал шаг в списке, «Шаг назад» или «Пройти ещё раз» —
   движок зовёт show(k), и модуль ставит экран в состояние шага k. Подсказка, куда нажать, — класс .pt-hint
   на нужном элементе (кольцо пульсирует, стили в case-proto.css). */
export type LiveCtx = {
  lang: "ru" | "en";
  /** «меньше движения»: без анимаций и пауз — состояния сменяются сразу */
  calm: boolean;
  /** import.meta.env.BASE_URL — для картинок из public */
  base: string;
  /** человек дошёл до шага k своим действием */
  go: (k: number) => void;
};
export type LiveInstance = {
  /** поставить экран в состояние шага k (переход по списку шагов, назад, заново) */
  show(k: number): void;
  destroy(): void;
};
export type LiveProto = {
  design: { w: number };
  mount(root: HTMLElement, ctx: LiveCtx): LiveInstance;
  /** 26.10: подготовка заранее, в простое браузера (стили экранов и т. п.) — чтобы на подъезде к блоку не было рывка */
  warm?(base: string): void;
};
